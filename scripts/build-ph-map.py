#!/usr/bin/env python3
"""Builds src/components/home/ph-map.ts from world-atlas countries-10m.json.

Usage: python3 scripts/build-ph-map.py path/to/countries-10m.json
Source: https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-10m.json
(Natural Earth 1:10m, public domain; world-atlas is ISC licensed).
"""
import json, math, sys

sys.setrecursionlimit(20000)
t = json.load(open(sys.argv[1]))
sx, sy = t["transform"]["scale"]
tx, ty = t["transform"]["translate"]


def decode(a):
    x = y = 0
    out = []
    for dx, dy in a:
        x += dx
        y += dy
        out.append((x * sx + tx, y * sy + ty))
    return out


arcs = [decode(a) for a in t["arcs"]]
arc = lambda i: arcs[i] if i >= 0 else arcs[~i][::-1]
g = next(o for o in t["objects"]["countries"]["geometries"] if o.get("properties", {}).get("name") == "Philippines")

rings = []
for poly in g["arcs"]:
    ring = []
    for i in poly[0]:
        p = arc(i)
        ring.extend(p if not ring else p[1:])
    rings.append(ring)

k = math.cos(math.radians(12.0))
minlon, maxlon, minlat, maxlat = 116.9, 126.7, 4.5, 21.2
W = 600
scale = W / ((maxlon - minlon) * k)
H = (maxlat - minlat) * scale
proj = lambda lon, lat: ((lon - minlon) * k * scale, (maxlat - lat) * scale)


def area(r):
    return abs(sum(r[i][0] * r[i - 1][1] - r[i - 1][0] * r[i][1] for i in range(len(r)))) / 2


def rdp(pts, eps):
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    den = math.hypot(x2 - x1, y2 - y1) or 1e-9
    dmax, idx = 0, 0
    for i in range(1, len(pts) - 1):
        x0, y0 = pts[i]
        d = abs((y2 - y1) * x0 - (x2 - x1) * y0 + x2 * y1 - y2 * x1) / den
        if d > dmax:
            dmax, idx = d, i
    if dmax > eps:
        return rdp(pts[: idx + 1], eps)[:-1] + rdp(pts[idx:], eps)
    return [pts[0], pts[-1]]


def simplify_ring(pr, eps):
    far = max(range(len(pr)), key=lambda i: math.dist(pr[0], pr[i]))
    a = rdp(pr[: far + 1], eps)
    b = rdp(pr[far:] + [pr[0]], eps)
    return a[:-1] + b[:-1]


groups = {"luzon": [], "visayas": [], "mindanao": []}
for r in rings:
    pr = [proj(*p) for p in r]
    if area(pr) < 10:
        continue
    cx = sum(p[0] for p in r) / len(r)
    cy = sum(p[1] for p in r) / len(r)
    if cy > 12.6 or cx < 120.4:
        grp = "luzon"
    elif cy < 9.9 and not (cx < 124.0 and cy > 9.4):
        grp = "mindanao"
    else:
        grp = "visayas"
    s = simplify_ring(pr, 0.9)
    if len(s) < 3:
        continue
    groups[grp].append("M" + " ".join(f"{x:.1f} {y:.1f}" for x, y in s) + "Z")

mx, my = proj(120.9842, 14.5995)  # Manila
lines = [
    "/**",
    " * Philippines outline for the About map. Natural Earth 1:10m (public domain)",
    " * via world-atlas@2.0.2 (ISC), simplified, equirectangular at 12°N.",
    " * Generated by scripts/build-ph-map.py; do not edit by hand.",
    " */",
    f'export const PH_VIEWBOX = "0 0 {W} {round(H)}";',
    f"export const MANILA = {{ x: {mx:.1f}, y: {my:.1f} }};",
    "",
    "export const phIslands = {",
]
for name, paths in groups.items():
    lines.append(f"  {name}: {json.dumps(' '.join(paths))},")
lines.append("} as const;")
open("src/components/home/ph-map.ts", "w").write("\n".join(lines) + "\n")
print({n: len(p) for n, p in groups.items()}, "bytes", sum(len(" ".join(p)) for p in groups.values()))
